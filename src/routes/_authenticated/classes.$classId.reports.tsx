import { createFileRoute } from "@tanstack/react-router";
import { useMemo, useState } from "react";
import { useAuth } from "@/lib/auth";
import {
  attendanceByStudent,
  useAssessments,
  useAttendance,
  useClass,
  useMarks,
  useOwnerName,
  useStudents,
} from "@/lib/data";
import { computeResult, emptyAttendance, fmt } from "@/lib/grading";
import { downloadCsv, downloadPdf, downloadXlsx, pdfPreviewUrl, type ReportMeta } from "@/lib/exports";
import { EmptyState, LedgerButton, Panel, PanelHeader } from "@/components/ledger";

export const Route = createFileRoute("/_authenticated/classes/$classId/reports")({
  head: () => ({
    meta: [
      { title: "Reports — Registrar" },
      { name: "description", content: "Generate the official PDF marksheet, Excel export and attendance reports." },
      { property: "og:title", content: "Reports — Registrar" },
      { property: "og:description", content: "Official marksheet, Excel export and attendance reports." },
    ],
  }),
  component: ReportsPage,
});

function ReportsPage() {
  const { classId } = Route.useParams();
  const { user } = useAuth();
  const { data: cls } = useClass(classId);
  const { data: facultyName } = useOwnerName(cls?.owner_id);
  const { data: students } = useStudents(classId);
  const { data: assessments } = useAssessments(classId);
  const { data: marks } = useMarks(classId);
  const { data: attendance } = useAttendance(classId);
  const isOwner = cls?.owner_id === user?.id;
  const [preview, setPreview] = useState<string | null>(null);

  const stats = attendanceByStudent(attendance?.sessions ?? [], attendance?.records ?? []);
  const scoresByStudent = useMemo(() => {
    const map: Record<string, Record<string, number | null>> = {};
    for (const m of marks ?? []) (map[m.student_id] ??= {})[m.assessment_id] = m.score;
    return map;
  }, [marks]);

  const columns = [
    "Name",
    "ID / Roll",
    "Attendance %",
    ...(assessments ?? []).map((a) => `${a.name} (${a.max_marks})`),
    "Total",
    "Percentage",
    "Grade",
  ];

  const rows = (students ?? []).map((s) => {
    const result = computeResult({
      assessments: assessments ?? [],
      scores: scoresByStudent[s.id] ?? {},
      attendance: stats[s.id] ?? emptyAttendance(attendance?.sessions.length ?? 0),
      weights: cls?.weights ?? {},
      scale: cls?.grading_scale ?? [],
    });
    return [
      s.name,
      s.roll,
      fmt(result.attendance.percentage),
      ...(assessments ?? []).map((a) => {
        const score = scoresByStudent[s.id]?.[a.id];
        return score === null || score === undefined ? "—" : score;
      }),
      `${result.rawTotal} / ${result.rawMax}`,
      fmt(result.percentage),
      result.grade,
    ];
  });

  const meta: ReportMeta = {
    heading: cls?.department ?? "Department",
    subheading: `Official Marksheet — ${cls?.subject ?? ""}`,
    lines: [
      `Section: ${cls?.section ?? ""}    Semester: ${cls?.semester ?? ""}    Academic year: ${cls?.academic_year ?? ""}`,
      `Faculty: ${facultyName ?? "—"}    Students: ${rows.length}    Attendance sessions: ${attendance?.sessions.length ?? 0}`,
    ],
  };

  const attColumns = ["Student", "ID / Roll", "Total classes", "Present", "Late", "Absent", "Percentage"];
  const attRows = (students ?? []).map((s) => {
    const st = stats[s.id];
    const total = attendance?.sessions.length ?? 0;
    return [
      s.name,
      s.roll,
      total,
      st?.present ?? 0,
      st?.late ?? 0,
      st?.absent ?? Math.max(0, total - (st?.present ?? 0) - (st?.late ?? 0)),
      `${fmt(st?.percentage ?? 0)}%`,
    ];
  });

  if (!isOwner) {
    return (
      <Panel>
        <PanelHeader title="Reports" />
        <EmptyState
          title="Faculty only"
          description="Official marksheets are generated by the faculty of this class. Your own result is in the Results tab."
        />
      </Panel>
    );
  }

  if (rows.length === 0) {
    return (
      <Panel>
        <PanelHeader title="Reports" />
        <EmptyState
          title="Nothing to report yet"
          description="Add students, assessments and marks, then generate the official marksheet here."
        />
      </Panel>
    );
  }

  const fileBase = `${cls?.subject ?? "class"}-${cls?.section ?? ""}-${cls?.semester ?? ""}`.replace(
    /[^\w\-]+/g,
    "-",
  );

  return (
    <div className="space-y-4">
      <Panel>
        <PanelHeader
          title="Official marksheet"
          hint="Preview, then generate and download"
          actions={
            <>
              <LedgerButton onClick={() => setPreview(pdfPreviewUrl(meta, columns, rows))}>
                Preview
              </LedgerButton>
              <LedgerButton
                variant="solid"
                onClick={() => downloadPdf(`marksheet-${fileBase}.pdf`, meta, columns, rows)}
              >
                Generate &amp; download PDF
              </LedgerButton>
              <LedgerButton
                onClick={() => downloadXlsx(`marksheet-${fileBase}.xlsx`, "Marksheet", columns, rows)}
              >
                Excel (.xlsx)
              </LedgerButton>
            </>
          }
        />
        <div className="space-y-2 p-4">
          <p className="text-[13px] text-mute">
            The marksheet carries the department, subject, section, semester, academic year, faculty
            name and, for each student, attendance, every assessment mark, total, percentage and letter
            grade — ready for submission.
          </p>
          {preview ? (
            <iframe title="Marksheet preview" src={preview} className="h-[560px] w-full rounded-md border border-border" />
          ) : null}
        </div>
      </Panel>

      <Panel>
        <PanelHeader
          title="Attendance report"
          actions={
            <>
              <LedgerButton onClick={() => downloadCsv(`attendance-${fileBase}.csv`, attColumns, attRows)}>
                CSV
              </LedgerButton>
              <LedgerButton
                onClick={() =>
                  downloadPdf(
                    `attendance-${fileBase}.pdf`,
                    { ...meta, subheading: `Attendance Report — ${cls?.subject ?? ""}` },
                    attColumns,
                    attRows,
                  )
                }
              >
                PDF
              </LedgerButton>
            </>
          }
        />
        <div className="p-4">
          <p className="text-[13px] text-mute">
            Student name, ID, total classes, present, late, absent and attendance percentage.
          </p>
        </div>
      </Panel>
    </div>
  );
}
